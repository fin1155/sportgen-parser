search_controls_ui <- function(queries) {
  disclosure("Поиск и фильтры",
    div(class = "search-grid",
      disclosure("Тема и источники",
        selectInput("research_profile", "Тема исследования", choices = setNames(names(RESEARCH_PROFILES), vapply(RESEARCH_PROFILES, `[[`, character(1), "label")), selected = "sports", width = "100%"),
        p(class = "field-help", "Тема подставляет пример запроса и набор колонок. Уточните запрос под свою задачу."),
        checkboxGroupInput("sources", "Источники", choices = c("PubMed" = "pubmed", "Elsevier" = "sciencedirect", "OpenAlex" = "openalex"), selected = c("pubmed", "sciencedirect", "openalex"), inline = TRUE),
        selectInput("openalex_scope", "Охват OpenAlex", choices = c("Российские и русскоязычные" = "russian", "Все страны и языки" = "global"), selected = "russian", width = "100%"),
        conditionalPanel("input.research_profile === 'sports'", checkboxInput("topic_filter", "Строгий фильтр: генетика и спорт", TRUE)), open = TRUE),
      disclosure("Годы и объём поиска",
        div(class = "year-range", textInput("year_from", "Год с", placeholder = "2020"), textInput("year_to", "Год по", placeholder = "2026")),
        p(class = "field-help", "Границы включаются в поиск. Можно заполнить только одну или оставить обе пустыми."),
        numericInput("max_records", "Статей на каждый источник", 200, min = 0, step = 1, width = "100%"),
        p(class = "field-help", "0 — максимум, разрешённый источником."),
        checkboxInput("fulltext", "Получать доступные полные тексты", TRUE),
        p(class = "field-help", "Полные тексты улучшают извлечение и увеличивают время поиска."), open = TRUE),
      disclosure("Поисковые запросы",
        p(class = "field-help", "Готовые запросы можно менять. AND — «и», OR — «или»."),
        disclosure("PubMed", textAreaInput("query_pubmed", NULL, queries$pubmed, rows = 4, width = "100%"), open = TRUE, class = "query-editor"),
        disclosure("Elsevier", textAreaInput("query_sciencedirect", NULL, queries$sciencedirect, rows = 4, width = "100%"), class = "query-editor"),
        disclosure("OpenAlex", textAreaInput("query_openalex", NULL, queries$openalex, rows = 4, width = "100%"), class = "query-editor"),
        actionButton("reset_queries", "Вернуть запросы темы", class = "btn-default"), open = TRUE)),
    disclosure("Ключ Elsevier и доступ",
      passwordInput("elsevier_key", "Свой ключ Elsevier", value = "", placeholder = "Серверный ключ или ключ текущего сеанса", width = "100%"),
      p(class = "field-help", "Введённый ключ действует только в сеансе. Если ScienceDirect недоступен, используется Scopus с фильтром Elsevier; способ получения указан в выдаче.")),
    id = "search-panel", class = "search-panel", open = TRUE)
}

