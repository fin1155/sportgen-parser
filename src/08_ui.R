# Full-width research workspace and native, keyboard-accessible disclosure groups.
disclosure <- function(title, ..., open = FALSE, id = NULL, class = "filter-group") {
  tags$details(id = id, class = class, open = if (open) NA else NULL,
    tags$summary(title), div(class = "disclosure-body", ...))
}

